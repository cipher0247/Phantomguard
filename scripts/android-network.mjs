// Generates the Android network security config. HTTPS (system CAs) is always allowed and TLS verification is never relaxed.
// Cleartext HTTP is allowed ONLY for loopback (adb reverse) and hosts you list in PG_LAN_HOST (comma-separated LAN IPs/names).
// Usage: PG_LAN_HOST=192.168.1.23 node scripts/android-network.mjs
import { writeFileSync, readFileSync } from 'node:fs';

const hosts = ['localhost', '127.0.0.1', ...(process.env.PG_LAN_HOST ?? '').split(',').map((h) => h.trim()).filter(Boolean)];
for (const h of hosts) if (!/^[A-Za-z0-9.-]+$/.test(h)) throw new Error(`Invalid host: ${h}`);
const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-network.mjs. Do not edit by hand. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors><certificates src="system" /></trust-anchors>
    </base-config>
    <domain-config cleartextTrafficPermitted="true">
${hosts.map((h) => `        <domain includeSubdomains="false">${h}</domain>`).join('\n')}
    </domain-config>
</network-security-config>
`;
writeFileSync('android/app/src/main/res/xml/network_security_config.xml', xml);

const mp = 'android/app/src/main/AndroidManifest.xml';
let m = readFileSync(mp, 'utf8');
if (!m.includes('networkSecurityConfig'))
  m = m.replace('android:allowBackup="true"', 'android:allowBackup="false"\n        android:usesCleartextTraffic="false"\n        android:networkSecurityConfig="@xml/network_security_config"');
writeFileSync(mp, m);
console.log(`Cleartext allowed only for: ${hosts.join(', ')}`);
